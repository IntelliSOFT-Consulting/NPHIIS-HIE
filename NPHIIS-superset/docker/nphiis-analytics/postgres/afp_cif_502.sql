    o.results_recv_obs  AS "Date Results received at national EPI",
    o.cell_results_obs  AS "Final cell culture results",
    o.sent_regional_obs AS "Date sent from National laboratory to regional lab results",
    o.itd_sent_obs      AS "Date IT differentiation sent to EPI",
    o.itd_recv_obs      AS "Date IT differentiation results received by EPI",
    TRIM(REGEXP_REPLACE(UPPER(COALESCE(o.county_obs,'')),'\\s+',' ','g'))    AS county_rls,
    TRIM(REGEXP_REPLACE(UPPER(COALESCE(o.subcounty_obs,'')),'\\s+',' ','g')) AS subcounty_rls
  FROM public.patient_flat_pg p
  JOIN public.patient_identifier_pg pi ON pi.id = p.id
    AND pi.system LIKE 'afp-%' AND pi.system NOT LIKE 'afp-contact%'
  LEFT JOIN o              ON o.patient_id  = p.id
  LEFT JOIN epid_identifier ei ON ei.patient_id = p.id
  LEFT JOIN submit_dates sd   ON sd.patient_id  = p.id
  LEFT JOIN lab_dates ld      ON ld.patient_id  = p.id
  WHERE p.active IS DISTINCT FROM false
)

