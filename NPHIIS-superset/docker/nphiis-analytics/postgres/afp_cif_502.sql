    MAX(CASE WHEN code = '525996604810'   THEN val END) AS ipop_obs,
    MAX(CASE WHEN code = '728034137219'   THEN val END) AS onset_obs,
    MAX(CASE WHEN code = '932108244312'   THEN val END) AS fever_obs,
    MAX(CASE WHEN code = '396371836778'   THEN val END) AS sudden_obs,
    MAX(CASE WHEN code = '917680711879'   THEN val END) AS progressive_obs,
    MAX(CASE WHEN code = '776980947995'   THEN val END) AS flaccid_obs,
    MAX(CASE WHEN code = '679475123276'   THEN val END) AS asymmetric_obs,
