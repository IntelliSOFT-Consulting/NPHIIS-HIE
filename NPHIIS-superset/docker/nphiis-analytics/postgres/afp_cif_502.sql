    o.ri_opv_total_obs  AS "Total OPV bOPV mOPV2 doses received through RI",
    o.sia_ipv_total_obs AS "Total IPV doses received through SIA",
    o.ri_ipv_total_obs  AS "Total IPV doses received through RI",
    o.last_ipv_obs      AS "Date of last IPV dose received through RI or SIA",
    o.vacc_source_obs   AS "Source of RI vaccination Information",
    o.immuno_obs        AS "Immunocompromised status suspected",
    o.spec1_obs         AS "Date 1st specimen collected",
    o.spec2_obs         AS "Date 2nd specimen collected",
    o.spec_sent_obs     AS "Date Specimen sent to the national level",
    o.lab_id_obs        AS "Lab ID No",
    o.spec_recv_obs     AS "Date specimen received at the national level",
    o.spec_status_obs   AS "Status of specimen at reception at the lab",
