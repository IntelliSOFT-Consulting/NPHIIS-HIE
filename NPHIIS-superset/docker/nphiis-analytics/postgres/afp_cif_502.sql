    o.res_subcounty_obs AS "DistrictofResidence",
    o.res_county_obs    AS "ProvinceOfResidence",
    o.res_ward_obs      AS "Residence Ward",
    o.village_obs       AS "Residence Village Estate Hse No",
    o.landmark_obs      AS "Neighborhood major landmark",
    o.nearest_hf_obs    AS "Name Nearest Health Facility",
    o.town_obs          AS "Town City Location",
    o.investigation_obs AS "Date of Investigation",
    o.notification_obs  AS "Date of Notification",
    o.notified_by_obs   AS "Notified by",
    o.admitted_obs      AS "Was the patient admitted",
    o.admission_date_obs AS "Date of admission",
    o.ipop_obs          AS "IP OP No",
    o.onset_obs         AS "Date of onset of paralysis",
    o.fever_obs         AS "Fever at onset of paralysis",
    o.sudden_obs        AS "Is paralysis of sudden onset",
    o.progressive_obs   AS "Progressive Paralysis less than 3 days",
    o.flaccid_obs       AS "Is paralysis flaccid floppy",
    o.asymmetric_obs    AS "Is the paralysis asymmetric",
    o.site_obs          AS "Site of paralysis",
    o.site_other_obs    AS "Specify other site of Paralysis",
