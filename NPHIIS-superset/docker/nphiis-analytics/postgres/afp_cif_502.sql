    o.injection_obs     AS "Was there any injection just before onset of paralysis",
    o.injection_site_obs AS "Site of injection",
    o.true_afp_obs      AS "After Investigation was this a true AFP",
    CASE
      WHEN LOWER(o.outcome_obs) IN ('alive','still hospitized','still hospitalized') THEN 1
      WHEN LOWER(o.outcome_obs) = 'dead'    THEN 2
      WHEN LOWER(o.outcome_obs) = 'unknown' THEN 9
      ELSE NULL
    END AS "Outcome",
    o.vaccinated_obs    AS "Was patient vaccinated against illness including campaign",
    o.doses_obs         AS "Number of doses administered Excluding birth OPV Dose",
    o.opv_birth_obs     AS "Date of OPV dose at birth",
