    MAX(CASE WHEN code = '722030957484'   THEN val END) AS itd_sent_obs,
    MAX(CASE WHEN code = '227970871286'   THEN val END) AS itd_recv_obs
  FROM obs_latest GROUP BY patient_id
),
submit_dates AS (
  SELECT patient_id, MIN(lu) AS case_submit FROM obs_norm GROUP BY patient_id
),
lab_dates AS (
  SELECT patient_id, MAX(lu) AS lab_submit
  FROM obs_norm
  WHERE code IN ('314664353334','482422649078','689825280680','294651853506','825243480539')
  GROUP BY patient_id
),
