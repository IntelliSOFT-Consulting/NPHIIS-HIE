    MAX(CASE WHEN code = '711388438654'   THEN val END) AS spec2_obs,
    MAX(CASE WHEN code = '808177332790'   THEN val END) AS spec_sent_obs,
    MAX(CASE WHEN code IN ('8732404074721','950699513538') THEN val END) AS lab_id_obs,
    MAX(CASE WHEN code = '689825280680'   THEN val END) AS spec_recv_obs,
    MAX(CASE WHEN code = '482422649078'   THEN val END) AS spec_status_obs,
    MAX(CASE WHEN code = '87324040799'    THEN val END) AS spec_reasons_obs,
    MAX(CASE WHEN code = '381386487834'   THEN val END) AS cell_culture_obs,
    MAX(CASE WHEN code = '294651853506'   THEN val END) AS results_sent_obs,
    MAX(CASE WHEN code = '825243480539'   THEN val END) AS results_recv_obs,
