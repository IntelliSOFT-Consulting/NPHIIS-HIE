/** Coding for a country given as an ISO alpha-2 code or a name; unknown input keeps its text. */
export function countryCoding(input: string): { system: string; code?: string; display: string } {
    const value = input.trim();
    const upper = value.toUpperCase();
    if (VHF_COUNTRIES[upper]) return { system: COUNTRY_SYSTEM, code: upper, display: VHF_COUNTRIES[upper] };
    const lower = value.toLowerCase();
    const alias = COUNTRY_ALIASES[lower];
    if (alias && VHF_COUNTRIES[alias]) return { system: COUNTRY_SYSTEM, code: alias, display: VHF_COUNTRIES[alias] };
    const match = Object.entries(VHF_COUNTRIES).find(([, display]) => display.toLowerCase() === lower);
    return match ? { system: COUNTRY_SYSTEM, code: match[0], display: match[1] } : { system: COUNTRY_SYSTEM, display: value };
}
